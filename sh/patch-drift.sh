#!/bin/bash
#=================================================
# Сверка исходников с патчами (подключается из WRT-part2.sh и WRT-part3.sh)
#
# В каждом diff патча есть строка «index <хеш до>..<хеш после>»: <хеш до> —
# git-хеш файла, на который патч написан. Если у автора файл с тех пор
# изменился, его текущий хеш другой — даже когда патч ещё ложится со
# сдвигом строк. Такой патч не применяется, он записывается в
# $GITHUB_WORKSPACE/patch_drift.txt, а workflow после part3 останавливает
# сборку и шлёт уведомление в Telegram: патч надо перевыпустить под новый
# код автора.
#
# Эталоны не хранятся отдельно — они в самих патчах, поэтому при обновлении
# патча обновляются сами. Важно: каждый патч серии должен быть снят с
# состояния после предыдущих патчей (git diff по очереди), иначе его
# «хеш до» не совпадёт и сработает ложно.
#
# PATCH_DRIFT_CHECK=0 — проверка выключена: прежнее поведение (патч,
# который не ложится, пропускается с предупреждением).
#=================================================

PATCH_DRIFT_FILE="${GITHUB_WORKSPACE:-.}/patch_drift.txt"

# patch_files <патч> — пути файлов, которые патч правит (кроме новых)
patch_files() {
    awk '/^--- a\// { p = $2; sub(/^a\//, "", p); print p }' "$1"
}

# patch_drift <патч> <каталог> [<пути пропущенных патчей, по строке>] —
# печатает по строке на каждый файл патча, который у автора изменился (или
# пропал). Пусто — исходники те же. Файл, который правит и пропущенный выше
# патч той же серии, помечается: он «другой», потому что тот патч не лёг.
patch_drift() {
    local _patch="$1" _dir="$2" _skipped="${3:-}" _h _f _cur
    # «--- a/<путь>» идёт после «index» в каждом diff; новый файл —
    # «--- /dev/null» (ему сверять нечего).
    awk '
        /^diff --git / { idx = ""; next }
        /^index [0-9a-f]+\.\.[0-9a-f]+/ { split($2, h, /\.\./); idx = h[1]; next }
        /^--- / { p = $2; sub(/^a\//, "", p); if (idx != "") print idx, p; idx = "" }
    ' "$_patch" | while read -r _h _f; do
        [ "$_f" = "/dev/null" ] && continue
        if [ ! -f "$_dir/$_f" ]; then
            echo "$_f (файла нет)"
            continue
        fi
        # --no-filters: хеш содержимого как есть, без преобразований
        # .gitattributes — так же его считал git diff при создании патча.
        _cur=$(git hash-object --no-filters -- "$_dir/$_f" 2>/dev/null)
        case "$_cur" in
        "$_h"*) ;;
        *)
            if [ -n "$_skipped" ] && printf '%s\n' "$_skipped" | grep -qxF -- "$_f"; then
                echo "$_f (после пропущенного патча)"
            else
                echo "$_f"
            fi ;;
        esac
    done
}

# patch_drift_record <фид|пакет> <имя> <патч> <файлы, по строке>
patch_drift_record() {
    local _files
    _files=$(printf '%s\n' "$4" | sed '/^$/d' | tr '\n' ',' | sed 's/,$//; s/,/, /g')
    printf '%s %s: %s — %s\n' "$1" "$2" "$3" "$_files" >> "$PATCH_DRIFT_FILE"
    echo "::error title=Патч устарел: $2/$3::У автора изменились файлы, к которым применяется патч: $_files"
}
